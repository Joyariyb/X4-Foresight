def load_merged_wares(idx: CatalogIndex):
    """Base wares.xml with every DLC's diff applied, in catalog order."""
    root = ET.fromstring(idx.read("libraries/wares.xml"))
    for vp in idx.find("extensions/*/libraries/wares.xml"):
        apply_diff(root, ET.fromstring(idx.read(vp)), source=vp)
    return root


def load_macro_prices(idx: CatalogIndex) -> dict[str, int]:
    """component macro id (lowercase) → average buy price, from wares.xml.

    Ships are sold as wares; each priced ware links back to its component via
    <component ref="..._macro"/>, so the ref IS the macro id. Used to price
    hulls in ship_stats. Equipment uses load_macro_price_ranges() instead —
    see its docstring for why a single number isn't enough there.
    """
    root = load_merged_wares(idx)
    prices: dict[str, int] = {}
    for w in root.findall("ware"):
        comp  = w.find("component")
        price = w.find("price")
        if comp is None or price is None:
            continue
        ref = (comp.get("ref") or "").lower()
        if ref:
            try:
                prices[ref] = int(price.get("average", 0))
            except (ValueError, TypeError):
                pass
    return prices


def load_macro_price_ranges(idx: CatalogIndex) -> dict[str, tuple[int, int, int]]:
    """component macro id (lowercase) → (min, average, max) buy price.

    Equipment-specific sibling of load_macro_prices(). The live in-game shop
    price observed during testing (e.g. 64718cr for a turret whose static
    range here was 43277-52894) runs ABOVE even the static max — there's a
    reputation/station markup the .cat files can't capture. A single
    "average" number would silently look more precise than it is; exposing
    the range is honest about that uncertainty for equipment tooltips.
    """
    root = load_merged_wares(idx)
    prices: dict[str, tuple[int, int, int]] = {}
    for w in root.findall("ware"):
        comp  = w.find("component")
        price = w.find("price")
        if comp is None or price is None:
            continue
        ref = (comp.get("ref") or "").lower()
        if not ref:
            continue
        try:
            min_raw = price.get("min", "0")
            min_v   = int(min_raw)
            avg_v   = int(price.get("average", 0))
            max_v   = int(price.get("max", 0))
            # Split Vendetta's shipped wares.xml has min="1536515365" for
            # shield_spl_m_standard_02_mk1 -- "15365" pasted twice in a row
            # (confirmed against the live, MD5-verified .cat/.dat archive, so
            # it's Egosoft's data bug, not a parsing one). A real price range
            # can never have min > max, so only when that invariant breaks do
            # we try undoing a same-length self-duplication in the min text.
            if min_v > max_v:
                half = len(min_raw) // 2
                if half and len(min_raw) % 2 == 0 and min_raw[:half] == min_raw[half:]:
                    min_v = int(min_raw[:half])
            prices[ref] = (min_v, avg_v, max_v)
        except (ValueError, TypeError):
            pass
    return prices


# Owner factions that never run a wharf/shipyard the player can buy from —
# Xenon and Kha'ak are permanently hostile; "ownerless" means no faction flies
# it at all (story/event-reward hulls). A hull owned ONLY by these is never
# sold, though Xenon/Kha'ak ones may still be captured by boarding (a runtime
# mechanic with no static-file flag, so we keep them in the catalog instead
# of dropping them).
_NON_PLAYER_FACTIONS = {"xenon", "khaak", "ownerless"}
_NO_BLUEPRINT_TAGS    = {"noblueprint", "noplayerblueprint", "noplayerbuild"}

# Owner sets meaning "no NPC faction ever flies this" — distinct from
# "ownerless" (a real derelict/event ship with no faction, but still a
# flyable hull someone might hand the player). "player" alone is a wares.xml
# scripting placeholder for internal mission/logistics props (e.g. the
# "transdrone" cargo bots) — nobody, including the player, ever pilots one in
# the normal sense, so unlike ownerless hulls these are dropped entirely
# rather than kept as capture-only. Cross-checked against qsna.eu's X4 ship
# builder, which omits exactly these macros.
_PLACEHOLDER_ONLY_OWNERS = {"player"}


def load_macro_availability(idx: CatalogIndex) -> dict[str, dict]:
    """component macro id (lowercase) → {"owners": set[str], "purchasable": bool}.

    Read from each ship's wares.xml <ware><owner faction="..."/></ware> entry.
    A macro is ABSENT from this dict — and load_ship_data() drops it entirely
    — if any of:
      * it has no <ware> entry at all (NPC skin variant, escape pod,
        colony-ship set-piece part, etc. — never offered to anyone),
      * its <ware> entry has zero <owner> factions (deployable drones,
        lasertowers, a handful of "_story" mission props — nobody in the
        game world is ever assigned to fly, sell, or guard them), or
      * its only owner is the "player" scripting placeholder (see
        _PLACEHOLDER_ONLY_OWNERS) — an internal prop, not a real ship.
    A macro present with purchasable=False has a real owner (so it's a flown,
    encounterable ship) but no faction the player can ever buy from — still
    a real ship the player could end up owning via capture or a story
    reward, so it stays in the catalog, just marked accordingly.
    """
    root = load_merged_wares(idx)
    out: dict[str, dict] = {}
    for w in root.findall("ware"):
        comp = w.find("component")
        if comp is None:
            continue
        ref = (comp.get("ref") or "").lower()
        if not ref:
            continue
        owners = {o.get("faction") for o in w.findall("owner") if o.get("faction")}
        if not owners or owners <= _PLACEHOLDER_ONLY_OWNERS:
            continue
        tags = set((w.get("tags") or "").split())
        purchasable = bool(owners - _NON_PLAYER_FACTIONS) and not (tags & _NO_BLUEPRINT_TAGS)
        out[ref] = {"owners": owners, "purchasable": purchasable}
    return out


def load_group_textids(idx: CatalogIndex) -> dict[str, int]:
    """
    waregroups.xml: group id → page 20215 base textId.
    e.g. "hightech" → 501; the factory display name sits at textId+3.
    """
    root = ET.fromstring(idx.read("libraries/waregroups.xml"))
    ids = {}
    for grp in root.findall("group"):
        m = _REF_RE.match(grp.get("name", ""))
        if m and m.group(1) == "20215":
            ids[grp.get("id")] = int(m.group(2))
    return ids


def select_wares(root) -> list:
    """
    The wares our tables cover: everything tagged "economy" (tradeable goods,
    including mineables and DLC wares) plus the explicit extras. Equipment,
    software, inventory items etc. are excluded — the scanner never sees them
    as cargo or production output.
    """
    out = []
    for w in root.findall("ware"):
        tags = (w.get("tags") or "").split()
        if "economy" in tags or w.get("id") in EXTRA_WARE_IDS:
            out.append(w)
    # Sorted by id so regeneration is deterministic → clean git diffs.
    out.sort(key=lambda w: w.get("id"))
    return out


