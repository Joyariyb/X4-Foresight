def main() -> int:
    game_dir = find_x4_install()
    if game_dir is None:
        print("FAIL: no X4 installation found — nothing generated.")
        return 1
    print(f"Reading game files from: {game_dir}")

    idx = CatalogIndex.from_game_dir(game_dir)

    # ── Wares (wares.xml + DLC diffs + waregroups.xml + t-file page 20201) ──
    wares_root = load_merged_wares(idx)
    wares = select_wares(wares_root)
    group_textids = load_group_textids(idx)
    # Page 20201 serves both the wares tables and station_names.
    texts_20201 = load_texts(idx, {"20201"})
    print(f"Selected {len(wares)} wares "
          f"({len(EXTRA_WARE_IDS)} via explicit extras list)")

    # ── Ships (ship macro XMLs + t-file pages 20101 + 20111) ────────────
    # 20101 — ship base names and full variant entries (refs to 20111)
    # 20111 — variant suffixes ("Vanguard", "Sentinel") and type qualifiers
    #         ("\(Gas\)", "\(Mineral\)") referenced inside the 20101 entries
    texts_ships = load_texts(idx, {"20101", "20111"})
    ships = load_ship_data(idx, texts_ships)
    print(f"Found {len(ships)} ship macros")

    # ── Station stats (structure modules + shields, page 20004 for sector names) ──
    # Page 20004 is also used by gen_sector_stats_py for display-name comments.
    texts_20004 = load_texts(idx, {"20004"})

    outputs = {
        "wares.py":            gen_wares_py(wares, group_textids, texts_20201),
        "ware_prices.py":      gen_ware_prices_py(wares),
        "production_stats.py": gen_production_stats_py(wares),
        "station_names.py":    gen_station_names_py(wares, texts_20201),
        "ships.py":            gen_ships_py(ships),
        "ship_stats.py":       gen_ship_stats_py(ships),
        "station_stats.py":    gen_station_stats_py(idx),
        "sector_stats.py":     gen_sector_stats_py(idx, texts_20004),
    }
    for fname, content in outputs.items():
        path = DATA_DIR / fname
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(REPO)}")

    print("\nDone — review with: git diff data/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
