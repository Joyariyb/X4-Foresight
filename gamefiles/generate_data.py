def _fmt_dict(name: str, type_hint: str, items: list[tuple[str, str]],
              comment: str = "") -> str:
    """Renders a dict literal with aligned values, one entry per line."""
    width = max((len(k) for k, _ in items), default=0) + 2  # +2 for quotes
    lines = [f"{name}: {type_hint} = {{"]
    for key, value in items:
        lines.append(f"    {('\"' + key + '\":').ljust(width + 1)} {value},")
    lines.append("}")
    return (comment + "\n" if comment else "") + "\n".join(lines) + "\n"


def gen_wares_py(wares, group_textids, texts) -> str:
    names, volumes, transports, groups = [], [], [], []
    for w in wares:
        wid = w.get("id")
        display = clean_text(w.get("name", ""), texts)
        names.append((wid, repr(display)))
        volumes.append((wid, f'{float(w.get("volume", "1")):.1f}'))
        transports.append((wid, repr(w.get("transport", "container"))))
        # WARE_GROUPS only covers wares buildable in a player station —
        # signalled in wares.xml by the presence of a factoryname reference.
        gid = group_textids.get(w.get("group", ""))
        if gid is not None and w.get("factoryname"):
            groups.append((wid, str(gid)))

    parts = [
        GENERATED_BANNER,
        _fmt_dict(
            "WARE_NAMES", "dict[str, str]", names,
            "\n# Ware id → display name (wares.xml name ref resolved via "
            "t/0001-l044.xml page 20201).\n"
            "# Used to label production modules and cargo; unknown ids fall "
            "back to title-case."),
        _fmt_dict(
            "WARE_VOLUME", "dict[str, float]", volumes,
            "\n# Ware id → volume in m³ per unit (wares.xml volume attribute)."
            "\n# Converts cargo amounts into m³ for storage fill percentages."),
        _fmt_dict(
            "WARE_TRANSPORT", "dict[str, str]", transports,
            "\n# Ware id → storage class: container / solid / liquid "
            "(wares.xml transport\n# attribute). Attributes trade "
            "reservations to the right storage type."),
        _fmt_dict(
            "WARE_GROUPS", "dict[str, int]", groups,
            "\n# Ware id → page 20215 base textId of its ware group "
            "(waregroups.xml).\n# Only wares with a factoryname in wares.xml "
            "(player-buildable) are listed.\n# The group factory display name "
            "lives at textId+3 — e.g. hightech 501 →\n# 504 \"High Tech "
            "Factory\" — the +3 offset X4 uses on this page."),
        PRIORITY_BLOCK,
    ]
    return "\n".join(parts)


def gen_ware_prices_py(wares) -> str:
    items = []
    for w in wares:
        p = w.find("price")
        if p is None:
            continue
        items.append((w.get("id"),
                      f'{{"min": {int(p.get("min", 0))}, '
                      f'"average": {int(p.get("average", 0))}, '
                      f'"max": {int(p.get("max", 0))}}}'))
    return GENERATED_BANNER + _fmt_dict(
        "WARE_PRICES", "dict[str, dict]", items,
        "\n# Ware id → market price band in credits (wares.xml <price>).\n"
        "# The station budget calculation values trade wares at the MAX "
        "price.")


def gen_production_stats_py(wares) -> str:
    blocks = []
    for w in wares:
        prods = w.findall("production")
        if not prods:
            continue  # mineables and pure trade goods have no recipe
        methods = []
        for prod in prods:
            inputs = {i.get("ware"): int(i.get("amount", 0))
                      for i in prod.findall("primary/ware")}
            input_str = ", ".join(f"'{k}': {v}" for k, v in sorted(inputs.items()))
            methods.append(f"            '{prod.get('method', 'default')}': "
                           f"{{{input_str}}},")
        # time/amount come from the FIRST (default) production entry; faction
        # methods only differ in inputs, which is all the methods dict holds.
        first = prods[0]
        blocks.append(
            f"    '{w.get('id')}': {{\n"
            f"        \"group\":   '{w.get('group', '')}',\n"
            f"        \"time\":    {int(float(first.get('time', 0)))},\n"
            f"        \"amount\":  {int(first.get('amount', 0))},\n"
            f"        \"methods\": {{\n" + "\n".join(methods) + "\n"
            f"        }},\n"
            f"    }},")
    return (GENERATED_BANNER +
            "\n# Ware id → production recipe (wares.xml <production> nodes)."
            "\n#   group   — ware category (wares.xml group attribute)"
            "\n#   time    — production cycle duration in seconds"
            "\n#   amount  — units produced per cycle"
            "\n#   methods — method id → {input ware: amount per cycle}."
            "\n#             'default' is the standard recipe; faction methods"
            "\n#             (teladi, split, ...) appear where inputs differ."
            "\n#             Empty dict = no inputs needed (energy cells).\n"
            "PRODUCTION_STATS: dict[str, dict] = {\n"
            + "\n".join(blocks) + "\n}\n")


