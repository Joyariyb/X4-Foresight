def gen_station_names_py(wares, texts) -> str:
    """
    Builds WARE_FACTORY_NAMES: ware_id → FactoryEntry(name, text_id).

    factoryname="{20201,N}" on each <ware> gives us the text_id (N). The
    factory display name sits at text_id itself on page 20201 (e.g. id 1204
    → "Hull Part Factory"). The ware display name sits at text_id-3 (1201 →
    "Hull Parts") — emitted as a comment so the file is self-documenting.
    Only wares with a factoryname reference are player-buildable and listed.
    """
    entries = []
    REF = re.compile(r'^\{(\d+),(\d+)\}$')
    for w in wares:
        fn = w.get("factoryname", "")
        m = REF.match(fn)
        if not m:
            continue
        text_id = int(m.group(2))
        factory_name = clean_text(texts.get(f"20201:{text_id}", ""), texts)
        ware_name    = clean_text(texts.get(f"20201:{text_id - 3}", ""), texts)
        if not factory_name:
            continue
        entries.append((w.get("id"), text_id, factory_name, ware_name,
                        w.get("group", "")))

    lines = [
        GENERATED_BANNER,
        "# Ware id → FactoryEntry(name, text_id) for player-buildable stations.",
        "# name     — factory display name from page 20201 of the language file",
        "# text_id  — page 20201 id; callers that need the ware display name",
        "#            find it at text_id-3 on the same page.",
        "#",
        "# Used by resolve_station_type() in scanner/language.py:",
        "#   • 1 unique ware produced → WARE_FACTORY_NAMES[ware_id].name",
        "#   • 2+ unique wares        → group factory name (data/wares.py WARE_GROUPS)",
        "",
        "from typing import NamedTuple",
        "",
        "",
        "class FactoryEntry(NamedTuple):",
        '    """Factory name and its page 20201 text ID from the X4 language file."""',
        "    name:    str  # display string, e.g. \"Hull Part Factory\"",
        "    text_id: int  # page 20201 id — ware display name is at text_id-3",
        "",
        "",
        "WARE_FACTORY_NAMES: dict[str, FactoryEntry] = {",
    ]
    # Group entries by ware group for readability, same as the hand-written file.
    from collections import defaultdict
    by_group = defaultdict(list)
    for eid, text_id, fname, wname, group in entries:
        by_group[group].append((eid, text_id, fname, wname))
    for group in sorted(by_group):
        lines.append(f"    # {group}")
        for eid, text_id, fname, wname in sorted(by_group[group]):
            lines.append(f'    "{eid}": FactoryEntry({repr(fname)}, {text_id}),'
                         f'  # display: {repr(wname)} (id {text_id - 3})')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


