def load_equipment(idx: CatalogIndex, bullets: dict[str, dict], prices: dict[str, tuple[int, int, int]]):
    """Returns (records, aliases, name_pages).

    records   list of {macro, slot, name_ref, ...stats} (name still unresolved)
    aliases   alias macro id → canonical macro id
    name_pages t-file page ids referenced by the identification names, so the
              caller knows which pages to load before resolving.
    """
    records: list[dict] = []
    aliases: dict[str, str] = {}
    name_pages: set[str] = set()

    paths = _glob(
        idx,
        # weapons + turrets (categorised under weaponsystems/<cat>/macros)
        "assets/props/weaponsystems/*/macros/*.xml",
        "extensions/*/assets/props/weaponsystems/*/macros/*.xml",
        # shields
        "assets/props/surfaceelements/macros/shield_*.xml",
        "extensions/*/assets/props/surfaceelements/macros/shield_*.xml",
        # engines + thrusters (both live under engines/macros)
        "assets/props/engines/macros/*.xml",
        "extensions/*/assets/props/engines/macros/*.xml",
    )

    for rel, root in _load_merged_roots(idx, paths):
        macro_el = root.find(".//macro")
        if macro_el is None:
            continue
        macro = macro_el.get("name", "").lower()
        cls   = macro_el.get("class", "")
        if not macro:
            continue

        ident = root.find(".//identification")
        # type="thrustertypes" is what separates a thruster from a main engine —
        # both carry class="engine".
        ident_type = ident.get("type", "") if ident is not None else ""

        # ── classify into a slot bucket ──────────────────────────────────────
        # missileturret/missilelauncher are real ship-hardpoint equipment, not
        # deployables -- confirmed via their component's hardpoint-mount tags
        # this session ("turret ... missile" / "...weapon...missile"), unlike
        # mines (deployable="1") or the spacesuit bomblauncher (a player EVA
        # item, mount tag "...spacesuit weapon"). They slot in exactly where
        # their name suggests: a launcher takes a weapon mount, a turret takes
        # a turret mount.
        if cls == "weapon":
            slot = "weapon"
        elif cls == "turret":
            slot = "turret"
        elif cls == "missilelauncher":
            slot = "weapon"
        elif cls == "missileturret":
            slot = "turret"
        elif cls == "shieldgenerator":
            slot = "shield"
        elif cls == "engine":
            slot = "thruster" if ident_type == "thrustertypes" else "engine"
        else:
            continue   # bullets, mines, effects, decorative — not equipment

        # ── an alias-only macro (no identification of its own) inherits from
        #    the macro it points at; record and resolve after concrete macros. ─
        if ident is None:
            ref = (macro_el.get("ref") or macro_el.get("alias") or "").lower()
            if ref:
                aliases[macro] = ref
            continue

        # hidden="1" marks equipment the game never shows the player (police
        # engines, drone/missile/escape-pod engines, mines). Not catalog items.
        if ident.get("hidden") == "1":
            continue

        rec: dict = {"macro": macro, "slot": slot}

        name_ref = ident.get("name", "")
        rec["name_ref"] = name_ref
        for page, _id in _REF_RE.findall(name_ref):
            name_pages.add(page)

        mk = _int(ident, "mk")
        if mk is not None:
            rec["mk"] = mk
        size = _size_from_macro(macro)
        if size:
            rec["size"] = size
        race = ident.get("makerrace")
        if race:
            rec["race"] = race
        price_range = prices.get(macro)
        if price_range:
            rec["price"] = price_range[1]       # average — unchanged existing behaviour
            rec["price_min"] = price_range[0]
            rec["price_max"] = price_range[2]   # live shop price can exceed even this

        # ── slot-specific stats ──────────────────────────────────────────────
        if slot in ("weapon", "turret"):
            rec["class"] = cls   # tells a missile-/regular- turret/weapon apart for the UI
            grp = _group_from_path(rel)
            if grp:
                rec["group"] = grp
            if (v := _int(root.find(".//rotationspeed"), "max"))      is not None: rec["rotation_speed"] = v
            if (v := _int(root.find(".//rotationacceleration"), "max")) is not None: rec["rotation_accel"] = v
            if (v := _int(root.find(".//hull"), "max"))               is not None: rec["hull_max"] = v
            if (v := _int(root.find(".//storage"), "capacity"))       is not None: rec["storage_capacity"] = v

            # damage/reload/heat-per-shot come from the referenced bullet (or
            # missile) macro
            bullet_el = root.find(".//bullet")
            bref = (bullet_el.get("class") or "").lower() if bullet_el is not None else ""
            rec.update(bullets.get(bref, {}))

            # Burst damage rate: weapon-class items use the FULL damage_shield
            # total (hull + shield bonus) x reload_rate as their headline --
            # confirmed against the Ion Blasters (756 shield x 0.5/s = 378,
            # matching the real tooltip) as well as every weapon-class item
            # with no shield bonus at all, where damage_shield == damage_hull
            # so this is equivalent to plain hull x rate (Behemoth Main
            # Battery, M/S Plasma Cannon, M Beam Emitter all matched this way).
            # Turret-class items use plain damage_hull x rate, EXCEPT
            # turret-class beams need an extra x4 on hull that the shield-bonus
            # formula doesn't explain (ARG M Beam Turret: 126 hull x4 x
            # 0.143/s = 72, matching the real tooltip; hull+shield=168 x rate
            # gives only 24, which does NOT match) -- still an open question,
            # not generalized further without more data points.
            rate = rec.get("reload_rate")
            if rate:
                if slot == "weapon":
                    base = rec.get("damage_shield")
                else:
                    base = rec.get("damage_hull")
                    if rec.get("is_beam") and base is not None:
                        base *= 4
                if base is not None:
                    rec["damage_rate_burst"] = _num(base * rate)

            # Heat: a second, independent throttle on top of the ammo clip,
            # only present on items with a weapon-level <heat> block (most
            # turrets don't have one in this dataset). Falls back to the
            # burst rate (never further throttled) when there's no heat data.
            heat_el = root.find(".//heat")
            heat_per_shot = rec.get("heat_per_shot")
            if heat_el is not None and heat_per_shot and rate:
                overheat = _float(heat_el, "overheat")
                coolrate = _float(heat_el, "coolrate")
                if overheat and coolrate:
                    initial           = rec.get("heat_initial") or 0.0
                    cooldelay         = _float(heat_el, "cooldelay") or 0.0
                    overheatcooldelay = _float(heat_el, "overheatcooldelay") or 0.0
                    avg_heat_rate = heat_per_shot * rate
                    if avg_heat_rate:
                        tto = (overheat - initial) / avg_heat_rate
                        cooldown = cooldelay + overheatcooldelay + overheat / coolrate
                        # 3dp, not 1dp -- same reasoning as _num(): the game
                        # truncates these to 1dp for its tooltip rather than
                        # rounding, so the UI needs the extra digits to
                        # reproduce that truncation itself.
                        rec["time_to_overheat"]  = round(tto, 3)
                        rec["cooldown_duration"] = round(cooldown, 3)
                        if rec.get("damage_rate_burst") is not None:
                            rec["damage_rate_sustained"] = _num(
                                rec["damage_rate_burst"] * tto / (tto + cooldown))
            if "damage_rate_sustained" not in rec and rec.get("damage_rate_burst") is not None:
                rec["damage_rate_sustained"] = rec["damage_rate_burst"]

        elif slot == "shield":
            recharge = root.find(".//recharge")
            if (v := _int(recharge, "max"))    is not None: rec["capacity"]       = v
            if (v := _int(recharge, "rate"))   is not None: rec["recharge_rate"]  = v
            # delay is genuinely fractional for several races (e.g. Argon M
            # 12.5s, Xenon L 17.25s) -- _int() was truncating it (12.5 -> 12),
            # silently wrong for ~25 macros; _round() (1dp) matches how the
            # file already handles every other non-integer stat.
            if (v := _round(recharge, "delay")) is not None: rec["recharge_delay"] = v
            # disruptionstability only appears on M/L/XL shields with their own
            # separate hull (not on "integrated" shields, which have no
            # standalone HP to disrupt) -- absence is meaningful, not missing data.
            if (v := _int(recharge, "disruptionstability")) is not None: rec["disruption_stability"] = v
            # The shield generator's own hit points -- same concept as
            # weapon/turret's hull_max above, just read from a different slot's
            # branch (shields use <hull integrated="1"/> instead when they
            # have no separate HP, so this is absent for those).
            if (v := _int(root.find(".//hull"), "max")) is not None: rec["hull_max"] = v

        elif slot == "engine":
            thrust = root.find(".//thrust")
            travel = root.find(".//travel")
            boost  = root.find(".//boost")
            if (v := _int(thrust, "forward"))    is not None: rec["thrust_forward"]  = v
            if (v := _int(thrust, "reverse"))    is not None: rec["thrust_reverse"]  = v
            if (v := _round(travel, "thrust"))   is not None: rec["travel_thrust"]   = v
            if (v := _round(travel, "charge"))   is not None: rec["travel_charge"]   = v
            if (v := _round(boost,  "thrust"))   is not None: rec["boost_thrust"]    = v
            if (v := _round(boost,  "duration")) is not None: rec["boost_duration"]  = v
            if (v := _round(boost,  "recharge")) is not None: rec["boost_recharge"]  = v
            # The engine's own hit points -- same concept as weapon/turret's and
            # shield's hull_max above, just read from this slot's branch. Absent
            # on "integrated" engines (S/M/XS sizes use <hull integrated="1"/>
            # instead -- no separate HP to damage; only L/XL have their own hull).
            if (v := _int(root.find(".//hull"), "max")) is not None: rec["hull_max"] = v

        elif slot == "thruster":
            thrust = root.find(".//thrust")
            if (v := _int(thrust, "strafe")) is not None: rec["strafe"] = v
            if (v := _int(thrust, "pitch"))  is not None: rec["pitch"]  = v
            if (v := _int(thrust, "yaw"))    is not None: rec["yaw"]    = v
            if (v := _int(thrust, "roll"))   is not None: rec["roll"]   = v

        # ── a macro can ALSO carry an alias= naming a second id that should
        #    resolve to this same definition (e.g. turret_arg_m_beam_01 →
        #    alias turret_arg_m_beam_02). Register alias → this macro. ─────────
        alias = (macro_el.get("alias") or "").lower()
        if alias and alias != macro:
            aliases[alias] = macro

        records.append(rec)

    return records, aliases, name_pages


