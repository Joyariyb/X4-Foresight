def _size_from_macro(macro: str) -> str | None:
    """The size token in a macro name, or None (e.g. lasertowers have none)."""
    toks = macro.split("_")
    for s in _SIZES:
        if s in toks:
            return s
    return None


def _group_from_path(vpath: str) -> str | None:
    """The weaponsystems category folder, e.g. .../weaponsystems/energy/... → 'energy'."""
    parts = vpath.split("/")
    try:
        return parts[parts.index("weaponsystems") + 1]
    except (ValueError, IndexError):
        return None


def _int(el, attr: str):
    """Attribute as int, or None if missing/blank/non-numeric."""
    if el is None:
        return None
    v = el.get(attr)
    try:
        return int(float(v)) if v not in (None, "") else None
    except (ValueError, TypeError):
        return None


def _round(el, attr: str, ndigits: int = 1):
    """Attribute as rounded float, or None if missing."""
    if el is None:
        return None
    v = el.get(attr)
    try:
        return round(float(v), ndigits) if v not in (None, "") else None
    except (ValueError, TypeError):
        return None


def _float(el, attr: str):
    """Attribute as unrounded float, or None if missing/blank/non-numeric."""
    if el is None:
        return None
    v = el.get(attr)
    try:
        return float(v) if v not in (None, "") else None
    except (ValueError, TypeError):
        return None


def _num(v):
    """Round to 3dp, then collapse to a plain int when that's exact (X4 damage/
    capacity values are almost always whole numbers; keeps the generated file's
    existing int-heavy style instead of sprouting '.0' on every multiplied value).
    3dp (not 1dp) so the UI has enough precision to truncate down to the in-game
    tooltip's displayed value instead of rounding to it -- the game truncates
    these derived stats, it doesn't round, so pre-rounding away the sub-tenth
    digits here would make that truncation impossible downstream."""
    if v is None:
        return None
    r = round(v, 3)
    return int(r) if r == int(r) else r


def _glob(idx: CatalogIndex, *patterns: str) -> list[str]:
    """Union of catalog matches for multiple wildcards."""
    seen: set[str] = set()
    for p in patterns:
        seen.update(idx.find(p))
    return sorted(seen)


_EXT_PREFIX_RE = re.compile(r'^extensions/[^/]+/')


def _load_merged_roots(idx: CatalogIndex, paths: list[str]) -> list[tuple[str, ET._Element]]:
    """Parses each catalog path, merging DLC files into their base-game
    counterpart at the same relative path before the caller ever sees them.

    Unlike wares.xml (one big file generate_data.py's load_merged_wares()
    diffs as a whole), equipment is one macro per file -- but a DLC can still
    ship a <diff> patching an existing base macro at the identical relative
    path (e.g. extensions/<dlc>/assets/.../weapon_x_macro.xml patching
    assets/.../weapon_x_macro.xml). Without this merge, that diff file was
    being parsed as its own standalone document and produced a second, sparse
    record for the same macro id -- the duplicate-equipment-entries bug.

    Returns (relative_path, merged_root) pairs, one per logical macro: base
    + merged diffs where a base file exists, or the DLC's own document where
    a DLC introduces a brand new macro (no base file to diff against).
    """
    by_relpath: dict[str, list[str]] = {}
    for vp in paths:
        rel = _EXT_PREFIX_RE.sub("", vp)
        by_relpath.setdefault(rel, []).append(vp)

    out: list[tuple[str, ET._Element]] = []
    for rel, group in by_relpath.items():
        # Base-game path (no extensions/ prefix) sorts first when present;
        # DLC diffs then apply on top of it in (deterministic) sorted order.
        group.sort(key=lambda vp: vp.startswith("extensions/"))
        root = ET.fromstring(idx.read(group[0]))
        for vp in group[1:]:
            patch_root = ET.fromstring(idx.read(vp))
            if patch_root.tag == "diff":
                apply_diff(root, patch_root, source=vp)
            else:
                # A second DLC shipping a full (non-diff) macro at the same
                # path is unexpected, but if it happens the later one wins --
                # same "later catalog overrides" rule the .cat index uses.
                root = patch_root
        out.append((rel, root))
    return out


